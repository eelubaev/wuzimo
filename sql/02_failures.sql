-- =====================================================================
-- 2-сұрақ. Транзакцияның сәтсіз аяқталуына әкелетін үш жағдай
-- ---------------------------------------------------------------------
-- Бұл жерде үйлестіру (2PC / Saga) ЖОҚ: әр жүйе өз транзакциясын
-- бөлек commit жасайды. Сондықтан бір қадам құласа, деректер
-- жүйелер арасында сәйкессіз күйде қалады.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1-жағдай. Бухгалтерия төлемді қабылдамайды (кезең жабық / жүйе қолжетімсіз)
-- ---------------------------------------------------------------------
\c payments_db
BEGIN;
INSERT INTO payments (payment_ref, student_id, amount) VALUES ('TX-0001', 3, 450000);
COMMIT;                                   -- төлем базасында жазба БАР

\c portal_db
BEGIN;
UPDATE students SET payment_status = 'PAID', updated_at = now() WHERE id = 3;
COMMIT;                                   -- кабинетте «Төленген»

\c accounting_db
BEGIN;
INSERT INTO ledger_entries (payment_ref, student_id, amount, period, entry_type)
VALUES ('TX-0001', 3, 450000, '2026-09', 'INCOME');   -- ҚАТЕ: кезең жабық
ROLLBACK;

-- Нәтиже: екі жүйеде төлем бар, бухгалтерияда жоқ -> сәйкессіздік
SELECT 'accounting_db' AS system, count(*) AS tx_0001_entries
FROM ledger_entries WHERE payment_ref = 'TX-0001';

-- ---------------------------------------------------------------------
-- 2-жағдай. Жеке кабинетте мәртебені жаңарту мүмкін емес
--           (студент табылмады / жазба құлыпталған)
-- ---------------------------------------------------------------------
\c portal_db
BEGIN;
DO $$
BEGIN
    UPDATE students SET payment_status = 'PAID', updated_at = now() WHERE id = 999;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Студент id=999 жүйеде табылмады';
    END IF;
END $$;                                   -- ҚАТЕ
ROLLBACK;

-- ---------------------------------------------------------------------
-- 3-жағдай. Деректер валидациядан өтпейді
--           (төлем қайталанды / сома дұрыс емес)
-- ---------------------------------------------------------------------
\c payments_db
BEGIN;
INSERT INTO payments (payment_ref, student_id, amount) VALUES ('TX-0001', 3, 450000);
-- ҚАТЕ: duplicate key (банк сол төлемді екінші рет жіберді)
ROLLBACK;

BEGIN;
INSERT INTO payments (payment_ref, student_id, amount) VALUES ('TX-0002', 3, -100);
-- ҚАТЕ: CHECK (amount > 0)
ROLLBACK;

-- ---------------------------------------------------------------------
-- 1-жағдайдан қалған сәйкессіз деректерді тазалау (келесі скрипттер үшін)
-- ---------------------------------------------------------------------
\c payments_db
DELETE FROM payments WHERE payment_ref = 'TX-0001';
\c portal_db
UPDATE students SET payment_status = 'UNPAID' WHERE id = 3;
